-- NTXP Contacts Database — initial schema (migration 0001), PostgreSQL dialect.
-- Mirrors 0001_init.sql: identity PKs, timestamptz, and a real contacts_fts
-- table with a generated tsvector + GIN index in place of SQLite's fts5.

-- ---------------------------------------------------------------------------
-- Canonical entities
-- ---------------------------------------------------------------------------

CREATE TABLE organizations (
    org_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL,
    name_norm   TEXT NOT NULL,
    website     TEXT,
    license_no  TEXT,
    attrs       TEXT NOT NULL DEFAULT '{}',
    is_deleted  INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_org_name_norm ON organizations(name_norm);

CREATE TABLE contacts (
    contact_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      BIGINT REFERENCES organizations(org_id),
    first_name  TEXT,
    last_name   TEXT,
    full_name   TEXT,
    name_norm   TEXT NOT NULL,
    block_key   TEXT,
    title       TEXT,
    attrs       TEXT NOT NULL DEFAULT '{}',
    is_deleted  INTEGER NOT NULL DEFAULT 0,
    merged_into BIGINT REFERENCES contacts(contact_id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_contact_name_norm ON contacts(name_norm);
CREATE INDEX ix_contact_org ON contacts(org_id);
CREATE INDEX ix_contact_block ON contacts(block_key);

-- ---------------------------------------------------------------------------
-- Multi-valued comms. Owned by a contact XOR an org.
-- ---------------------------------------------------------------------------

CREATE TABLE emails (
    email_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id  BIGINT REFERENCES contacts(contact_id),
    org_id      BIGINT REFERENCES organizations(org_id),
    email       TEXT NOT NULL,
    email_norm  TEXT NOT NULL,
    is_invalid  INTEGER NOT NULL DEFAULT 0,
    is_primary  INTEGER NOT NULL DEFAULT 0,
    CHECK ((contact_id IS NOT NULL) <> (org_id IS NOT NULL))
);
CREATE UNIQUE INDEX ux_email_owner
    ON emails(email_norm, COALESCE(contact_id, 0), COALESCE(org_id, 0));
CREATE INDEX ix_email_norm ON emails(email_norm);
CREATE INDEX ix_email_contact ON emails(contact_id);

CREATE TABLE phones (
    phone_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id  BIGINT REFERENCES contacts(contact_id),
    org_id      BIGINT REFERENCES organizations(org_id),
    phone_raw   TEXT NOT NULL,
    phone_e164  TEXT,
    kind        TEXT NOT NULL DEFAULT 'main',
    CHECK ((contact_id IS NOT NULL) <> (org_id IS NOT NULL))
);
CREATE UNIQUE INDEX ux_phone_owner
    ON phones(COALESCE(phone_e164, phone_raw), kind, COALESCE(contact_id, 0), COALESCE(org_id, 0));
CREATE INDEX ix_phone_e164 ON phones(phone_e164);
CREATE INDEX ix_phone_contact ON phones(contact_id);

CREATE TABLE addresses (
    address_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_id  BIGINT REFERENCES contacts(contact_id),
    org_id      BIGINT REFERENCES organizations(org_id),
    line1       TEXT,
    city        TEXT,
    state       TEXT,
    zip         TEXT,
    addr_norm   TEXT NOT NULL,
    kind        TEXT NOT NULL DEFAULT 'main',
    CHECK ((contact_id IS NOT NULL) <> (org_id IS NOT NULL))
);
CREATE UNIQUE INDEX ux_addr_owner
    ON addresses(addr_norm, COALESCE(contact_id, 0), COALESCE(org_id, 0));
CREATE INDEX ix_addr_org ON addresses(org_id);

-- ---------------------------------------------------------------------------
-- Controlled-vocabulary tags / classifications
-- ---------------------------------------------------------------------------

CREATE TABLE tags (
    tag_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind    TEXT NOT NULL,
    value   TEXT NOT NULL,
    UNIQUE (kind, value)
);

CREATE TABLE entity_tags (
    tag_id      BIGINT NOT NULL REFERENCES tags(tag_id),
    entity_type TEXT NOT NULL,
    entity_id   BIGINT NOT NULL,
    PRIMARY KEY (tag_id, entity_type, entity_id)
);
CREATE INDEX ix_entity_tags_entity ON entity_tags(entity_type, entity_id);

-- ---------------------------------------------------------------------------
-- Provenance + idempotency anchor
-- ---------------------------------------------------------------------------

CREATE TABLE source_records (
    source_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source        TEXT NOT NULL,
    source_pk     TEXT,
    row_hash      TEXT NOT NULL,
    raw           TEXT NOT NULL,
    contact_id    BIGINT REFERENCES contacts(contact_id),
    org_id        BIGINT REFERENCES organizations(org_id),
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source, source_pk, row_hash)
);
CREATE INDEX ix_src_resolved ON source_records(source, source_pk);

CREATE TABLE staging_records (
    staging_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source      TEXT NOT NULL,
    row_hash    TEXT NOT NULL,
    payload     TEXT NOT NULL,
    confidence  REAL,
    status      TEXT NOT NULL DEFAULT 'pending',
    note        TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source, row_hash)
);

-- ---------------------------------------------------------------------------
-- Bi-directional sync
-- ---------------------------------------------------------------------------

CREATE TABLE external_ids (
    system         TEXT NOT NULL,
    external_id    TEXT NOT NULL,
    contact_id     BIGINT REFERENCES contacts(contact_id),
    org_id         BIGINT REFERENCES organizations(org_id),
    remote_hash    TEXT,
    last_synced_at TIMESTAMPTZ,
    sync_state     TEXT NOT NULL DEFAULT 'linked',
    PRIMARY KEY (system, external_id),
    CHECK ((contact_id IS NOT NULL) <> (org_id IS NOT NULL))
);
CREATE INDEX ix_extid_contact ON external_ids(contact_id);
CREATE INDEX ix_extid_org ON external_ids(org_id);

CREATE TABLE change_log (
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type TEXT NOT NULL,
    entity_id   BIGINT NOT NULL,
    field       TEXT,
    op          TEXT NOT NULL,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    origin      TEXT NOT NULL
);
CREATE INDEX ix_changelog_entity ON change_log(entity_type, entity_id);

CREATE TABLE sync_state (
    system      TEXT PRIMARY KEY,
    last_seq    BIGINT NOT NULL DEFAULT 0,
    last_pull_at TIMESTAMPTZ
);

-- ---------------------------------------------------------------------------
-- Full-text search: real table with a generated tsvector + GIN index.
-- Repository inserts (entity_type, entity_id, text); tsv is derived.
-- ---------------------------------------------------------------------------

CREATE TABLE contacts_fts (
    entity_type TEXT NOT NULL,
    entity_id   BIGINT NOT NULL,
    text        TEXT,
    tsv         tsvector GENERATED ALWAYS AS (to_tsvector('simple', COALESCE(text, ''))) STORED
);
CREATE INDEX ix_fts_tsv ON contacts_fts USING GIN(tsv);
CREATE INDEX ix_fts_entity ON contacts_fts(entity_type, entity_id);
