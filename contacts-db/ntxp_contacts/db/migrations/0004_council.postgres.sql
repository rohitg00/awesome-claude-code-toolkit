-- NTXP Contacts — migration 0004 (PostgreSQL): persisted model-council answers.

CREATE TABLE council_answers (
    answer_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        TEXT NOT NULL,
    question    TEXT NOT NULL,
    choice      TEXT,
    confidence  DOUBLE PRECISION NOT NULL DEFAULT 0,
    cost        DOUBLE PRECISION NOT NULL DEFAULT 0,
    mode        TEXT NOT NULL,
    voters      TEXT,
    provenance  TEXT NOT NULL,
    options     TEXT,
    contact_id  BIGINT REFERENCES contacts(contact_id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_council_created ON council_answers(created_at);
CREATE INDEX ix_council_contact ON council_answers(contact_id);
